// Autostart for each platform, as a plan of explicit steps: files to write and commands to run.
// setup.js prints the plan, asks before anything privileged, and re-running produces the same
// files at the same paths, so a service is never registered twice.
import os from 'node:os';
import nodePath from 'node:path';

// Units, plists and init scripts are for POSIX systems: build their paths with POSIX separators even
// when the plan is computed elsewhere (tests on Windows).
const path = nodePath.posix;

export const LABEL = 'io.github.tjabooo.lilin';
const q = (s) => (/[\s"'\\$`]/.test(s) ? `"${String(s).replace(/(["\\$`])/g, '\\$1')}"` : s);

// systemd: waits for the network and, when MEDIA_DIR is a separate mount, for that mount, so a
// slow NAS share doesn't make Lilin start with an empty library.
export function systemdUnit({ appDir, node, user = null, mediaDir = null, dataDir = null }) {
  const mounts = [mediaDir, dataDir].filter(Boolean).map((d) => q(d)).join(' ');
  return `[Unit]
Description=Lilin media server
Documentation=https://github.com/Tjabooo/lilin
Wants=network-online.target
After=network-online.target${mounts ? `\nRequiresMountsFor=${mounts}` : ''}

[Service]
Type=simple
${user ? `User=${user}\n` : ''}WorkingDirectory=${q(appDir)}
ExecStart=${q(node)} ${q(path.join(appDir, 'server.js'))}
Restart=on-failure
RestartSec=5
# Lilin stops cleanly on SIGTERM; ffmpeg helpers in the same cgroup are stopped with it.
KillMode=control-group
TimeoutStopSec=20
${user ? 'NoNewPrivileges=true\nPrivateTmp=true\n' : ''}
[Install]
WantedBy=${user ? 'multi-user.target' : 'default.target'}
`;
}

export function launchdPlist({ appDir, node }) {
  const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>${LABEL}</string>
  <key>ProgramArguments</key>
  <array><string>${esc(node)}</string><string>${esc(path.join(appDir, 'server.js'))}</string></array>
  <key>WorkingDirectory</key><string>${esc(appDir)}</string>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>
  <key>ThrottleInterval</key><integer>10</integer>
  <key>StandardOutPath</key><string>${esc(path.join(appDir, 'logs', 'lilin.log'))}</string>
  <key>StandardErrorPath</key><string>${esc(path.join(appDir, 'logs', 'lilin.log'))}</string>
</dict>
</plist>
`;
}

export function openrcScript({ appDir, node, user }) {
  return `#!/sbin/openrc-run
# Lilin media server (generated by setup.js)
name="lilin"
description="Lilin media server"
directory=${q(appDir)}
command=${q(node)}
command_args=${q(path.join(appDir, 'server.js'))}
command_user=${q(user)}
command_background=true
pidfile="/run/lilin.pid"
output_log=${q(path.join(appDir, 'logs', 'lilin.log'))}
error_log=${q(path.join(appDir, 'logs', 'lilin.log'))}

depend() {
  need net
  after localmount netmount
}
`;
}

// The plan for an action on this machine. `scope` is 'user' or 'system' (systemd only).
export function servicePlan(action, {
  manager, appDir, node = process.execPath, scope = 'system', user = os.userInfo().username,
  home = os.homedir(), mediaDir = null, dataDir = null,
}) {
  const steps = [];
  const step = (description, extra) => steps.push({ description, privileged: false, ...extra });

  if (manager === 'task-scheduler') {
    const script = nodePath.win32.join(appDir, 'scripts', 'windows', action === 'restart' ? 'restart-lilin.ps1' : 'install-service.ps1');
    const flag = { install: [], status: ['-Status'], uninstall: ['-Uninstall'], restart: [] }[action];
    step({ install: 'Register the Lilin scheduled task, runs as you without admin rights (asks for your Windows password)',
      status: 'Show the scheduled tasks', uninstall: 'Remove the Lilin scheduled task', restart: 'Restart the Lilin task' }[action],
    { cmd: ['powershell.exe', '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', script, ...flag], privileged: action === 'install' || action === 'uninstall', interactive: action === 'install' });
    return steps;
  }

  if (manager === 'systemd') {
    const userScope = scope === 'user';
    const unitPath = userScope ? path.join(home, '.config', 'systemd', 'user', 'lilin.service') : '/etc/systemd/system/lilin.service';
    const ctl = userScope ? ['systemctl', '--user'] : ['systemctl'];
    const priv = !userScope;
    if (action === 'install') {
      step(`Write ${unitPath}`, { write: { path: unitPath, content: systemdUnit({ appDir, node, user: userScope ? null : user, mediaDir, dataDir }) }, privileged: priv });
      step('Reload systemd', { cmd: [...ctl, 'daemon-reload'], privileged: priv });
      step('Enable and start lilin.service', { cmd: [...ctl, 'enable', '--now', 'lilin.service'], privileged: priv });
      if (userScope) step('Keep your user services running after logout and start them at boot', { cmd: ['loginctl', 'enable-linger', user] });
    } else if (action === 'status') {
      step('Show service status', { cmd: [...ctl, 'status', '--no-pager', '--lines=5', 'lilin.service'], allowFail: true });
    } else if (action === 'restart') {
      step('Restart lilin.service', { cmd: [...ctl, 'restart', 'lilin.service'], privileged: priv });
    } else if (action === 'uninstall') {
      step('Stop and disable lilin.service', { cmd: [...ctl, 'disable', '--now', 'lilin.service'], privileged: priv, allowFail: true });
      step(`Remove ${unitPath}`, { remove: unitPath, privileged: priv });
      step('Reload systemd', { cmd: [...ctl, 'daemon-reload'], privileged: priv });
    }
    return steps;
  }

  if (manager === 'launchd') {
    const plist = path.join(home, 'Library', 'LaunchAgents', `${LABEL}.plist`);
    const uid = typeof process.getuid === 'function' ? process.getuid() : 501;
    const target = `gui/${uid}`;
    if (action === 'install') {
      step(`Write ${plist}`, { write: { path: plist, content: launchdPlist({ appDir, node }) }, mkdir: path.join(appDir, 'logs') });
      step('Unload a previous copy, if any', { cmd: ['launchctl', 'bootout', `${target}/${LABEL}`], allowFail: true });
      step('Load and start it', { cmd: ['launchctl', 'bootstrap', target, plist] });
    } else if (action === 'status') {
      step('Show the launch agent', { cmd: ['launchctl', 'print', `${target}/${LABEL}`], allowFail: true, quiet: true });
    } else if (action === 'restart') {
      step('Restart the launch agent', { cmd: ['launchctl', 'kickstart', '-k', `${target}/${LABEL}`] });
    } else if (action === 'uninstall') {
      step('Stop the launch agent', { cmd: ['launchctl', 'bootout', `${target}/${LABEL}`], allowFail: true });
      step(`Remove ${plist}`, { remove: plist });
    }
    return steps;
  }

  if (manager === 'openrc') {
    const script = '/etc/init.d/lilin';
    if (action === 'install') {
      step(`Write ${script}`, { write: { path: script, content: openrcScript({ appDir, node, user }), mode: 0o755 }, privileged: true });
      step('Start Lilin at boot', { cmd: ['rc-update', 'add', 'lilin', 'default'], privileged: true });
      step('Start it now', { cmd: ['rc-service', 'lilin', 'restart'], privileged: true });
    } else if (action === 'status') {
      step('Show service status', { cmd: ['rc-service', 'lilin', 'status'], allowFail: true });
    } else if (action === 'restart') {
      step('Restart Lilin', { cmd: ['rc-service', 'lilin', 'restart'], privileged: true });
    } else if (action === 'uninstall') {
      step('Stop Lilin', { cmd: ['rc-service', 'lilin', 'stop'], privileged: true, allowFail: true });
      step('Remove it from boot', { cmd: ['rc-update', 'del', 'lilin', 'default'], privileged: true, allowFail: true });
      step(`Remove ${script}`, { remove: script, privileged: true });
    }
    return steps;
  }

  throw new Error(`No supported service manager (${manager || 'none found'}). Start Lilin with "npm start" from a terminal multiplexer or your own init system.`);
}

// How a step looks when printed: the exact command, with sudo shown where it will be used.
export function describeStep(s, { sudo = false } = {}) {
  const pre = s.privileged && sudo ? 'sudo ' : '';
  if (s.cmd) return `${pre}${s.cmd.map(q).join(' ')}`;
  if (s.write) return `${pre ? 'sudo ' : ''}write ${s.write.path}`;
  if (s.remove) return `${pre ? 'sudo ' : ''}rm ${s.remove}`;
  return s.description;
}
